"""Environment check - run this first, before anything else.

    python scripts/check_env.py

It verifies the Python version, that every required package imports at the
right version, that all data/artifact files are present, that the saved models
actually load and predict, and that the figures exist. Anything wrong is
printed with a concrete fix.

Exit code 0 = everything is ready. 1 = something needs fixing.
"""
from __future__ import annotations

import importlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

OK, WARN, BAD = "OK  ", "WARN", "FAIL"
problems: list[str] = []
warnings: list[str] = []


def line(status: str, label: str, detail: str = "") -> None:
    colour = {"OK  ": "\033[92m", "WARN": "\033[93m", "FAIL": "\033[91m"}.get(status, "")
    reset = "\033[0m" if colour else ""
    print(f"  [{colour}{status}{reset}] {label:<34} {detail}")


def section(title: str) -> None:
    print(f"\n{title}")
    print("-" * 74)


# --------------------------------------------------------------------------
section("1. Python interpreter")
# --------------------------------------------------------------------------
v = sys.version_info
print(f"  Python {v.major}.{v.minor}.{v.micro}  ({sys.executable})")
if v < (3, 10):
    line(BAD, "Python version", "need 3.10+  →  install a newer Python")
    problems.append("Upgrade Python to 3.10 or newer (3.11 or 3.12 is ideal).")
elif v >= (3, 14):
    line(WARN, "Python version", f"{v.major}.{v.minor} is very new; 3.11-3.13 is better tested")
    warnings.append("Python 3.14+ may lack prebuilt wheels for some packages.")
else:
    line(OK, "Python version", "supported")

in_venv = sys.prefix != sys.base_prefix
line(OK if in_venv else WARN, "Virtual environment",
     "active" if in_venv else "NOT active (works, but a venv is recommended)")

# --------------------------------------------------------------------------
section("2. Required packages")
# --------------------------------------------------------------------------
REQUIRED = [
    ("numpy", "1.24"),
    ("pandas", "2.0"),
    ("sklearn", "1.3"),
    ("matplotlib", "3.7"),
    ("seaborn", "0.12"),
    ("joblib", "1.3"),
    ("streamlit", "1.30"),
]
OPTIONAL = [
    ("docx", "1.1", "python-docx", "rebuilding the Word report"),
    ("nbformat", "5.9", "nbformat", "rebuilding the notebook"),
    ("nbclient", "0.8", "nbclient", "executing the notebook"),
]

missing_required = []
for mod, minver in REQUIRED:
    try:
        m = importlib.import_module(mod)
        ver = getattr(m, "__version__", "?")
        try:
            good = tuple(int(x) for x in ver.split(".")[:2]) >= tuple(int(x) for x in minver.split("."))
        except Exception:
            good = True
        line(OK if good else WARN, mod, f"{ver}" + ("" if good else f"  (need >= {minver})"))
        if not good:
            warnings.append(f"{mod} {ver} is older than the recommended {minver}.")
    except ImportError:
        line(BAD, mod, "NOT INSTALLED")
        missing_required.append(mod)

for mod, minver, pkg, purpose in OPTIONAL:
    try:
        m = importlib.import_module(mod)
        line(OK, mod, f"{getattr(m, '__version__', '?')}")
    except ImportError:
        line(WARN, mod, f"missing - only needed for {purpose}")
        warnings.append(f"Optional package '{pkg}' missing: cannot rebuild the {'report' if mod=='docx' else 'notebook'}.")

if missing_required:
    problems.append("Install dependencies:  pip install -r requirements.txt")

# --------------------------------------------------------------------------
section("3. Project files")
# --------------------------------------------------------------------------
FILES = [
    ("data/raw_ai4i2020.csv", True, "raw dataset"),
    ("src/config.py", True, "configuration"),
    ("src/cleaning.py", True, "cleaning pipeline"),
    ("src/modeling.py", True, "models"),
    ("src/plots.py", True, "figures"),
    ("src/train.py", True, "training entry point"),
    ("app/streamlit_app.py", True, "dashboard"),
    ("artifacts/models.joblib", True, "trained models (pre-built)"),
    ("artifacts/results.json", True, "metrics (pre-built)"),
    ("data/clean_ai4i2020.csv", False, "cleaned data (regenerated by training)"),
    ("data/synthetic_corrupted_ai4i.csv", False, "corrupted test copy"),
    ("notebooks/01_failure_prediction_walkthrough.ipynb", False, "notebook"),
    ("reports/failure_prediction_report.md", False, "report (Markdown)"),
    ("reports/failure_prediction_report.docx", False, "report (Word)"),
]
for rel, critical, desc in FILES:
    p = ROOT / rel
    if p.exists():
        size = p.stat().st_size
        human = f"{size/1024/1024:.1f} MB" if size > 1024 * 1024 else f"{size/1024:.0f} KB"
        line(OK, rel, f"{human}  ({desc})")
    else:
        line(BAD if critical else WARN, rel, f"MISSING  ({desc})")
        if critical:
            problems.append(f"Required file missing: {rel}")
        else:
            warnings.append(f"{rel} missing - regenerate it (see the guide).")

n_figs = len(list((ROOT / "artifacts" / "figures").glob("*.png")))
line(OK if n_figs >= 14 else WARN, "artifacts/figures/*.png", f"{n_figs} figures")

# --------------------------------------------------------------------------
section("4. Trained model sanity check")
# --------------------------------------------------------------------------
if (ROOT / "artifacts" / "models.joblib").exists() and not missing_required:
    try:
        import joblib
        import numpy as np

        from src import cleaning, config as C, modeling

        import warnings as _w

        with _w.catch_warnings(record=True) as caught:
            _w.simplefilter("always")
            bundle = joblib.load(ROOT / "artifacts" / "models.joblib")
            mismatched = [
                w for w in caught
                if "InconsistentVersionWarning" in type(w.message).__name__
            ]

        trained_ver = bundle.get("library_versions", {}).get("scikit-learn")
        import sklearn as _sk

        if mismatched:
            line(
                WARN,
                "model/library version",
                f"trained with sklearn {trained_ver}, you have {_sk.__version__}"
                "  → run: python -m src.train",
            )
            warnings.append(
                "The saved models were built with scikit-learn "
                f"{trained_ver} but you have {_sk.__version__}. Predictions still work; "
                "run 'python -m src.train' for an exact match."
            )
        else:
            line(OK, "model/library version", f"scikit-learn {trained_ver} (matches)")
        line(OK, "models loaded", f"{len(bundle['models'])} models: {', '.join(bundle['models'])}")
        line(OK, "best model", bundle["best_model"])
        line(OK, "features expected", str(len(bundle["feature_names"])))

        # End-to-end inference on one synthetic-but-valid machine
        raw = cleaning.read_raw()
        row = raw.iloc[[0]].copy()
        cleaned, _, _ = cleaning.clean(row)
        featured = cleaning.build_features(cleaned)
        X, _, _ = modeling.build_design_matrix(featured)
        X = X.reindex(columns=bundle["feature_names"], fill_value=0.0)
        probs = {k: float(m.predict_proba(X)[:, 1][0]) for k, m in bundle["models"].items()}
        line(OK, "end-to-end prediction", ", ".join(f"{k}={v:.3f}" for k, v in probs.items()))
        assert all(0.0 <= p <= 1.0 for p in probs.values())
        line(OK, "probabilities valid", "all within [0, 1]")
    except Exception as exc:
        line(BAD, "model sanity check", f"{type(exc).__name__}: {exc}")
        problems.append(f"The saved model could not be used: {exc}. Try: python -m src.train")
else:
    line(WARN, "model sanity check", "skipped (missing models or packages)")

# --------------------------------------------------------------------------
section("5. Dashboard readiness")
# --------------------------------------------------------------------------
if missing_required:
    line(BAD, "streamlit", "cannot launch until packages are installed")
else:
    line(OK, "streamlit", "available - launch with:  streamlit run app/streamlit_app.py")
port_note = (
    "If port 8501 is busy, run:  streamlit run app/streamlit_app.py --server.port 8502"
)
print(f"  note: {port_note}")

# --------------------------------------------------------------------------
section("SUMMARY")
# --------------------------------------------------------------------------
if problems:
    print(f"\n  \033[91m{len(problems)} problem(s) to fix:\033[0m")
    for p in problems:
        print(f"    • {p}")
if warnings:
    print(f"\n  \033[93m{len(warnings)} warning(s):\033[0m")
    for w in warnings:
        print(f"    • {w}")
if not problems:
    print("\n  \033[92m✓ Your environment is ready.\033[0m\n")
    print("  Next steps:")
    print("    1) streamlit run app/streamlit_app.py     → open the dashboard")
    print("    2) python -m src.train                    → rebuild everything (~60s)")
    print("    3) jupyter notebook notebooks/            → read the walkthrough")
    sys.exit(0)

print("\n  Fix the problems above, then re-run:  python scripts/check_env.py\n")
sys.exit(1)
